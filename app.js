/* ---------- Stratagem timing ("timing" field) and phase ("phases" field) ---------- */
const PHASE_ORDER = ['command', 'movement', 'shooting', 'charge', 'fight'];
const TURNS = [['yourTurn', 'Your'], ['oppTurn', "Opponent's"]];
function phaseLabel(p) { return String(p || '').charAt(0).toUpperCase() + String(p || '').slice(1); }
/* Turn per phase, read from the WHEN text: "Your Shooting phase" -> yourTurn, "your opponent's Shooting phase"
   -> oppTurn, "the Fight phase" / "Fight phase" (no owner) -> the data "timing" value (anyTurn = both turns).
   Only phases listed in the data "phases" field are used; phases not found in the text keep the data timing.
   Returns [{ turn, phase }], phase "any" = every phase. */
const PHASE_RE = /\b(your\s+opponent[’']?s?|opponent[’']?s?|your)?\s*((?:command|movement|shooting|charge|fight)(?:\s*(?:,|or|and|\/)\s*(?:the\s+)?(?:command|movement|shooting|charge|fight))*)\s+phases?\b/gi;
const usageCache = new WeakMap();
function stratUsage(s) {
  if (usageCache.has(s)) return usageCache.get(s);
  const dataPh = arr(s.phases);
  const dflt = s.timing || 'anyTurn';
  let out = [];
  const d = document.createElement('div');
  d.innerHTML = String(s.when || '');
  const text = d.textContent.replace(/\s+/g, ' ');
  const anyData = !dataPh.length || dataPh.includes('any');
  const anyText = /\bany (?:of (your(?: opponent[’']?s?)?) )?phases?\b/i.exec(text);
  const found = new Map();
  let m;
  PHASE_RE.lastIndex = 0;
  while ((m = PHASE_RE.exec(text))) {
    const q = (m[1] || '').toLowerCase();
    const turn = /opponent/.test(q) ? 'oppTurn' : q === 'your' ? 'yourTurn' : dflt;
    for (const p of m[2].toLowerCase().match(/command|movement|shooting|charge|fight/g)) {
      if (!anyData && !dataPh.includes(p)) continue;
      const prev = found.get(p);
      found.set(p, prev && prev !== turn ? 'anyTurn' : turn);
    }
  }
  if (anyText || (anyData && !found.size)) {
    /* "Any phase", "End of any of your phases", "any of your opponent's phases" */
    const q = (anyText && anyText[1] || '').toLowerCase();
    out = [{ turn: /opponent/.test(q) ? 'oppTurn' : q ? 'yourTurn' : dflt, phase: 'any' }];
  } else if (anyData) {
    for (const [p, turn] of found) out.push({ turn, phase: p });
  } else {
    for (const p of dataPh) out.push({ turn: found.get(p) || dflt, phase: p });
  }
  usageCache.set(s, out);
  return out;
}
function usageMatches(s, t, p) {
  return stratUsage(s).some(u => (!t || u.turn === t || u.turn === 'anyTurn') && (!p || u.phase === p || u.phase === 'any'));
}
/* Tag groups with the filter words, one group per turn: e.g. [Your][Shooting]  [Your][Opponent's][Fight] */
function usageTags(s) {
  const groups = new Map();
  for (const u of stratUsage(s)) {
    if (!groups.has(u.turn)) groups.set(u.turn, []);
    groups.get(u.turn).push(u.phase);
  }
  const order = ['yourTurn', 'oppTurn', 'anyTurn'];
  return [...groups.entries()].sort((a, b) => order.indexOf(a[0]) - order.indexOf(b[0])).map(([turn, phases]) => {
    const tags = [];
    if (turn === 'yourTurn' || turn === 'anyTurn') tags.push(['your', 'Your']);
    if (turn === 'oppTurn' || turn === 'anyTurn') tags.push(['opp', "Opponent's"]);
    if (phases.includes('any')) tags.push(['ph', 'All phases']);
    else for (const p of phases.sort((a, b) => PHASE_ORDER.indexOf(a) - PHASE_ORDER.indexOf(b))) tags.push(['ph', phaseLabel(p)]);
    return tags;
  });
}

const stratIndex = [];
