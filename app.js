/* All detachment entries of a faction */
function factionDetachments(fac) {
  const fu = factionUnits(fac);
  const list = [];
  for (const d of fu.detachments) {
    if (isAllySource(fac, d.src)) continue;
    const visitGroup = (g, depth) => {
      if (!g || depth > 4) return;
      for (const e of arr(g.selectionEntries)) list.push({ e, src: d.src });
      for (const sg of arr(g.selectionEntryGroups)) visitGroup(sg, depth + 1);
      for (const l of arr(g.entryLinks)) {
        const x = deref(l, fac.scope);
        if (!x) continue;
        if (l.type === 'selectionEntryGroup') visitGroup(x, depth + 1); else list.push({ e: x, src: d.src });
      }
    };
    for (const g of arr(d.node.selectionEntryGroups)) visitGroup(g, 0);
    for (const l of arr(d.node.entryLinks)) if (l.type === 'selectionEntryGroup') visitGroup(deref(l, fac.scope), 0);
    for (const e of arr(d.node.selectionEntries)) list.push({ e, src: d.src });
  }
  const seen = new Set();
  return list.filter(x => !x.e.hidden && !hiddenForFaction(x.e, fac) && !seen.has(x.e.id) && seen.add(x.e.id)).sort((a, b) => a.e.name.localeCompare(b.e.name));
}

/* True when a "hidden" modifier hides the entry for this faction, judged only by
   primary-catalogue conditions (e.g. chapter-specific detachments). */
function hiddenForFaction(node, fac) {
  const ev = (g) => {
    const parts = arr(g.conditions).map(c => {
      if (c.scope !== 'primary-catalogue') return null;
      const is = fac.id === c.childId;
      return c.type === 'instanceOf' ? is : c.type === 'notInstanceOf' ? !is : null;
    }).concat(arr(g.conditionGroups).map(ev));
    if (!parts.length) return null;
    if (g.type === 'or') return parts.some(p => p === true) ? true : parts.some(p => p === null) ? null : false;
    return parts.some(p => p === false) ? false : parts.some(p => p === null) ? null : true;
  };
  return arr(node.modifiers).some(m => m.field === 'hidden' && (m.value === true || m.value === 'true') &&
    ev({ type: 'and', conditions: arr(m.conditions), conditionGroups: arr(m.conditionGroups) }) === true);
}

