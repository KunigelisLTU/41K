function idbOpen() {
  return new Promise((res, rej) => {
    let r;
    try { r = indexedDB.open(IDB.name, 1); } catch (e) { rej(e); return; }
    r.onupgradeneeded = () => r.result.createObjectStore(IDB.store);
    r.onsuccess = () => res(r.result);
    r.onerror = () => rej(r.error);
  });
}
async function idbGet(key) {
  const db = await idbOpen();
  return new Promise((res, rej) => {
    const q = db.transaction(IDB.store, 'readonly').objectStore(IDB.store).get(key);
    q.onsuccess = () => res(q.result); q.onerror = () => rej(q.error);
  });
}
async function idbPut(key, val) {
  const db = await idbOpen();
  return new Promise((res, rej) => {
    const tx = db.transaction(IDB.store, 'readwrite');
    tx.objectStore(IDB.store).put(val, key);
    tx.oncomplete = () => res(); tx.onerror = () => rej(tx.error); tx.onabort = () => rej(tx.error);
  });
}
function isNewer(a, b) {
  if (!a || !a.date) return false;
  if (!b || !b.date) return true;
  return new Date(a.date) > new Date(b.date);
}
function loadScript(src) {
  return new Promise((res, rej) => {
    const s = document.createElement('script');
    s.src = src; s.charset = 'utf-8';
    s.onload = res; s.onerror = () => rej(new Error('Cannot load ' + src));
    document.head.appendChild(s);
  });
}

/* Uses the browser copy when it is newer than data/bsdata.js, otherwise loads data/bsdata.js */
async function loadData() {
  const bundled = window.BSDATA_VERSION || null;
  let cached = null;
  try { cached = await idbGet(IDB.key); } catch (e) { cached = null; }
  const useCache = () => {
    window.BSDATA = cached.files.map(f => ({ file: f.file, data: JSON.parse(f.text) }));
    window.BSDATA_VERSION = cached.version;
  };
  const hasCache = cached && arr(cached.files).length;
  if (hasCache && isNewer(cached.version, bundled)) {
    try { useCache(); return; } catch (e) { console.warn(e); }
  }
  try {
    await loadScript('data/bsdata.js');
  } catch (e) {
    /* no bundled data (e.g. hosted without data/bsdata.js): use the browser copy if there is one */
    if (hasCache) { useCache(); return; }
    window.BSDATA_VERSION = null;
    throw e;
  }
}

/* Stratagems: data/stratagems.js, replaced by a newer browser copy if there is one */
async function loadStratagems() {
  try { await loadScript('data/stratagems.js'); } catch (e) { /* optional */ }
  let cached = null;
  try { cached = await idbGet(STRAT.key); } catch (e) { cached = null; }
  if (cached && cached.text && isNewer(cached.version, window.STRAT_VERSION)) {
    try { window.STRATDATA = JSON.parse(cached.text); window.STRAT_VERSION = cached.version; } catch (e) { console.warn(e); }
  }
}

function setStatus(html, title) {
  const el = $('#dataStatus');
  if (!el) return;
  el.innerHTML = html || '';
  el.title = title || '';
  el.hidden = !html;
}
function renderVersion() {
  const v = window.BSDATA_VERSION || {};
  const parts = [Data.gs ? Data.gs.name : ''];
  if (v.date) parts.push(String(v.date).slice(0, 10));
  if (v.sha) parts.push(String(v.sha).slice(0, 7));
  $('.brand-sub').textContent = parts.filter(Boolean).join(' · ');
  $('.brand-sub').title = [v.repo, v.sha || v.source, v.built].filter(Boolean).join(' · ');
}

async function latestCommit(repo, branch) {
  const r = await fetch(`https://api.github.com/repos/${repo}/commits/${branch}`, { headers: { Accept: 'application/vnd.github+json' } });
  if (!r.ok) throw new Error('GitHub ' + r.status);
  const c = await r.json();
  return { repo, branch, sha: c.sha, date: c.commit && c.commit.committer && c.commit.committer.date };
}

/* Returns the new version when stratagems were downloaded, otherwise null */
async function updateStratagems() {
  const latest = await latestCommit(STRAT.repo, STRAT.branch);
  const cur = window.STRAT_VERSION || {};
  if (cur.sha === latest.sha || !isNewer(latest, cur)) return null;
  const res = await fetch(`https://raw.githubusercontent.com/${STRAT.repo}/${latest.sha}/${STRAT.file}`);
  if (!res.ok) throw new Error(STRAT.file + ': ' + res.status);
  const text = await res.text();
  JSON.parse(text);
  latest.file = STRAT.file;
  latest.built = new Date().toISOString();
  latest.source = 'browser';
  await idbPut(STRAT.key, { version: latest, text });
  return latest;
}

let updating = false;
async function checkForUpdate(manual, onDone) {
  if (updating) return;
  if (!manual && Date.now() - store.get('lastCheck', 0) < CHECK_EVERY_MS) return;
  updating = true;
  try {
    setStatus('Checking…');
    let stratNew = null;
    try { stratNew = await updateStratagems(); } catch (e) { console.warn('Stratagems', e); }
    const latest = await latestCommit(REPO, BRANCH);
    store.set('lastCheck', Date.now());
    const cur = window.BSDATA_VERSION || {};
    if (cur.sha === latest.sha || !isNewer(latest, cur)) {
      if (stratNew) { setStatus(`<button class="linkbtn" data-reload>Stratagems ${esc(String(stratNew.date).slice(0, 10))} · Reload</button>`); return; }
      setStatus(manual ? 'Up to date' : '');
      if (manual) setTimeout(() => setStatus(''), 3000);
      return;
    }

    const tr = await fetch(`https://api.github.com/repos/${REPO}/git/trees/${latest.sha}?recursive=1`, { headers: { Accept: 'application/vnd.github+json' } });
    if (!tr.ok) throw new Error('GitHub ' + tr.status);
    const tree = await tr.json();
    const paths = arr(tree.tree).filter(t => t.type === 'blob' && /\.json$/i.test(t.path) && !/^\.github\//.test(t.path)).map(t => t.path);
    if (!paths.length) throw new Error('No data files');

    const files = new Array(paths.length);
    let next = 0, done = 0;
    setStatus(`Downloading 0/${paths.length}`);
    const worker = async () => {
      while (next < paths.length) {
        const i = next++;
        const p = paths[i];
        const res = await fetch(`https://raw.githubusercontent.com/${REPO}/${latest.sha}/${p.split('/').map(encodeURIComponent).join('/')}`);
        if (!res.ok) throw new Error(p + ': ' + res.status);
        const text = await res.text();
        JSON.parse(text);
        files[i] = { file: p.split('/').pop(), text };
        setStatus(`Downloading ${++done}/${paths.length}`);
      }
    };
    await Promise.all(Array.from({ length: 6 }, worker));
    files.sort((a, b) => a.file.localeCompare(b.file));
    latest.built = new Date().toISOString();
    latest.source = 'browser';
    await idbPut(IDB.key, { version: latest, files });
    setStatus(`<button class="linkbtn" data-reload>${esc(String(latest.date).slice(0, 10))} · ${esc(latest.sha.slice(0, 7))} · Reload</button>`);
    if (onDone) onDone();
  } catch (e) {
    console.warn(e);
    setStatus('Update failed', e.message);
  } finally {
    updating = false;
  }
}

