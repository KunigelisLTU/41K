/* 40k Codex — browser for BSData (Warhammer 40,000 11th edition) data.
   Data: window.BSDATA (generated by build.ps1). */
'use strict';

/* =====================================================================
   Helpers
   ===================================================================== */
const $ = (s, r = document) => r.querySelector(s);
const esc = s => String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const arr = x => (Array.isArray(x) ? x : []);
const store = {
  get(k, d) { try { const v = localStorage.getItem('codex.' + k); return v == null ? d : JSON.parse(v); } catch (e) { return d; } },
  set(k, v) { try { localStorage.setItem('codex.' + k, JSON.stringify(v)); } catch (e) { /* ignore */ } },
};

/* BSData description formatting: **bold**, ^^keyword^^, line breaks */
function fmt(text) {
  let s = esc(String(text || '').trim());
  s = s.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>');
  s = s.replace(/\^\^(.+?)\^\^/g, '<span class="kwtext">$1</span>');
  s = s.replace(/\r?\n/g, '<br>');
  return s;
}

/* Entries not shown in the Codex view (Crusade, upgrades, etc.) */
const SKIP_RE = /^(crusade|weapon modifications?|enhancements?|battle honours?|battle scars?|order of battle|show\/hide|detachment rules)\b/i;
const CAT_ORDER = ['Epic Hero', 'Character', 'Battleline', 'Infantry', 'Mounted', 'Beast', 'Swarm', 'Monster', 'Vehicle', 'Dedicated Transport', 'Fortification'];

/* =====================================================================
   Data model
   ===================================================================== */
const Data = { cats: {}, list: [], gs: null, ptsId: null, factions: [], allIndexed: false };

function initData() {
  for (const f of window.BSDATA) {
    const raw = f.data.gameSystem || f.data.catalogue;
    if (!raw) continue;
    const cat = { id: raw.id, name: raw.name, file: f.file, raw, isGs: !!f.data.gameSystem, library: !!raw.library, index: null };
    Data.cats[cat.id] = cat;
    Data.list.push(cat);
    if (cat.isGs) Data.gs = cat;
  }
  const pts = arr(Data.gs && Data.gs.raw.costTypes).find(t => t.name === 'pts');
  Data.ptsId = pts ? pts.id : null;
  for (const cat of Data.list) cat.scope = buildScope(cat);

  Data.factions = Data.list.filter(c => !c.isGs && !c.library).map(c => {
    const parts = c.name.split(' - ');
    let group = parts.length > 1 ? parts[0] : 'Other';
    let label = parts.length > 1 ? parts.slice(1).join(' - ') : c.name;
    let sub = '';
    if (/^Adeptus Astartes - /.test(label)) { sub = 'Adeptus Astartes'; label = label.replace(/^Adeptus Astartes - /, ''); }
    return { cat: c, group, label, sub };
  }).sort((a, b) => (a.group + a.sub + a.label).localeCompare(b.group + b.sub + b.label));
}

/* Catalogue scope: itself, linked catalogues (recursive) and the game system */
function buildScope(cat) {
  const out = [], seen = new Set();
  const q = [cat];
  while (q.length) {
    const c = q.shift();
    if (!c || seen.has(c.id)) continue;
    seen.add(c.id); out.push(c);
    for (const l of arr(c.raw.catalogueLinks)) q.push(Data.cats[l.targetId]);
  }
  if (Data.gs && !seen.has(Data.gs.id)) out.push(Data.gs);
  return out;
}

/* Index id -> object. Shared lists first, then everything else. */
function ensureIndex(cat) {
  if (cat.index) return cat.index;
  const idx = new Map();
  const r = cat.raw;
  for (const key of ['sharedSelectionEntries', 'sharedSelectionEntryGroups', 'sharedProfiles', 'sharedRules', 'sharedInfoGroups', 'categoryEntries', 'selectionEntries'])
    for (const o of arr(r[key])) if (o && o.id && !idx.has(o.id)) idx.set(o.id, o);
  const walk = o => {
    if (Array.isArray(o)) { for (const x of o) walk(x); return; }
    if (!o || typeof o !== 'object') return;
    if (o.id && o.name && !o.targetId && !idx.has(o.id) && (o.type || o.typeName || o.description != null || o.characteristics)) idx.set(o.id, o);
    for (const k in o) { const v = o[k]; if (v && typeof v === 'object') walk(v); }
  };
  walk(r);
  cat.index = idx;
  return idx;
}

function resolve(id, scope) {
  for (const c of scope) { const n = ensureIndex(c).get(id); if (n) return { node: n, cat: c }; }
  for (const c of Data.list) { const n = ensureIndex(c).get(id); if (n) return { node: n, cat: c }; }
  return null;
}

/* entryLink + its target -> one merged node */
function deref(link, scope) {
  const r = resolve(link.targetId, scope);
  if (!r) return null;
  const t = r.node;
  const cat = (k) => arr(t[k]).concat(arr(link[k]));
  return Object.assign({}, t, {
    name: link.name || t.name,
    hidden: !!(link.hidden || t.hidden),
    entryLinks: cat('entryLinks'), infoLinks: cat('infoLinks'), profiles: cat('profiles'), rules: cat('rules'),
    modifiers: cat('modifiers'), modifierGroups: cat('modifierGroups'), constraints: cat('constraints'),
    categoryLinks: cat('categoryLinks'),
    costs: arr(link.costs).length ? link.costs : t.costs,
    _targetId: t.id, _src: r.cat,
  });
}

/* =====================================================================
   Faction unit list
   ===================================================================== */
const unitCache = new Map();

function factionUnits(fcat) {
  if (unitCache.has(fcat.id)) return unitCache.get(fcat.id);
  const roots = [], seen = new Set();
  const visit = (c) => {
    if (!c || seen.has(c.id)) return;
    seen.add(c.id);
    for (const l of arr(c.raw.entryLinks)) roots.push({ link: l, src: c });
    for (const e of arr(c.raw.selectionEntries)) roots.push({ entry: e, src: c });
    for (const cl of arr(c.raw.catalogueLinks)) if (cl.importRootEntries) visit(Data.cats[cl.targetId]);
  };
  visit(fcat);

  const units = [], detachments = [], ids = new Set();
  for (const r of roots) {
    let node;
    if (r.link) { if (r.link.type && r.link.type !== 'selectionEntry') continue; node = deref(r.link, fcat.scope); }
    else node = Object.assign({}, r.entry, { _targetId: r.entry.id, _src: r.src });
    if (!node || node.hidden) continue;
    if (ids.has(node._targetId)) continue;
    if (node.type === 'unit' || node.type === 'model') {
      ids.add(node._targetId);
      const catLinks = arr(node.categoryLinks).filter(l => !l.hidden);
      const prim = catLinks.find(l => l.primary);
      units.push({
        id: node._targetId, name: node.name, node, fac: fcat, src: r.src,
        own: r.src === fcat, ally: isAllySource(fcat, r.src),
        primary: prim ? prim.name : (catLinks.some(l => l.name === 'Character') ? 'Character' : 'Other'),
        catIds: new Set(catLinks.map(l => l.targetId)),
        cats: catLinks.map(l => l.name),
        legends: /\[legends\]/i.test(node.name),
      });
    } else if (node.type === 'upgrade' && /detachment/i.test(node.name)) {
      ids.add(node._targetId);
      detachments.push({ node, src: r.src });
    }
  }

  /* Leader / Support associations: category id -> units that can join */
  const joinIndex = new Map();
  for (const u of units) {
    for (const a of arr(u.node.associations)) {
      for (const t of assocTargets(a)) {
        if (!joinIndex.has(t.id)) joinIndex.set(t.id, []);
        joinIndex.get(t.id).push({ unit: u, label: a.label || a.name });
      }
    }
  }
  const res = { units, detachments, joinIndex };
  unitCache.set(fcat.id, res);
  return res;
}

/* Ally catalogues (Agents, Knights, Titans, ...) unless it is the faction's own library */
const ALLY_RE = /Agents of the Imperium|Imperial Knights|Chaos Knights|Titans|Unaligned|Daemons Library|Heresy Legends/i;
function isAllySource(fcat, src) {
  if (src === fcat || !ALLY_RE.test(src.name)) return false;
  const core = src.name.replace(/^(Imperium|Chaos|Xenos|Library|Aeldari)\s*-\s*/i, '').replace(/\s*-?\s*Library$/i, '').replace(/^Chaos\s+/i, '').trim();
  return !(core && fcat.name.toLowerCase().includes(core.toLowerCase()));
}

function assocTargets(a) {
  const out = [];
  const visit = (o) => {
    for (const c of arr(o.conditions)) if (c.type === 'instanceOf' && c.childId) out.push({ id: c.childId, name: c.childName || '' });
    for (const g of arr(o.conditionGroups)) visit(g);
  };
  visit(a);
  return out;
}

/* =====================================================================
   Datasheet building
   ===================================================================== */
const sheetCache = new Map();

function charMap(p) {
  const m = {};
  for (const c of arr(p.characteristics)) m[c.name] = c.$text != null ? String(c.$text) : '';
  return m;
}
function isCondHidden(mods) {
  return arr(mods).some(m => m.field === 'hidden' && (m.value === true || m.value === 'true') && (arr(m.conditions).length || arr(m.conditionGroups).length));
}
function applyNameMods(name, mods) {
  for (const m of arr(mods)) {
    if (m.field === 'name' && m.type === 'append' && !arr(m.conditions).length && !arr(m.conditionGroups).length) name += ' ' + m.value;
    if (m.field === 'name' && m.type === 'set' && !arr(m.conditions).length && !arr(m.conditionGroups).length) name = String(m.value);
  }
  return name;
}
function costOf(node, typeId) {
  const c = arr(node.costs).find(c => c.typeId === typeId);
  return c ? Number(c.value) || 0 : 0;
}
function bounds(node) {
  let min = null, max = null;
  for (const c of arr(node.constraints)) {
    if (c.field !== 'selections' || (c.scope !== 'parent' && c.scope !== 'self')) continue;
    const v = Number(c.value);
    if (c.type === 'min') min = Math.max(min || 0, v);
    if (c.type === 'max') max = v < 0 ? Infinity : (max == null ? v : Math.min(max, v));
  }
  return { min, max };
}

function buildSheet(u) {
  const key = u.fac.id + '|' + u.id;
  if (sheetCache.has(key)) return sheetCache.get(key);
  const scope = u.fac.scope;
  const S = {
    unit: u, statlines: [], ranged: new Map(), melee: new Map(), abilities: new Map(), rules: new Map(),
    other: new Map(), options: [], comp: [], modelIds: new Set(), modelNames: new Set(), upgradeCosts: [],
    modelGroupIds: new Set(), modelCatIds: new Set(), allIds: new Set(),
  };

  const addProfile = (p, ctx, mods) => {
    if (!p || p.hidden) return;
    const name = applyNameMods(p.name, mods);
    const ch = charMap(p);
    const type = p.typeName || '';
    if (type === 'Unit') {
      const k = name + JSON.stringify(ch);
      if (!S.statlines.some(s => s.key === k)) S.statlines.push({ key: k, name, ch });
    } else if (type === 'Ranged Weapons' || type === 'Melee Weapons') {
      const map = type === 'Ranged Weapons' ? S.ranged : S.melee;
      const k = name + '|' + JSON.stringify(ch);
      if (!map.has(k)) map.set(k, { name, ch, carriers: new Set() });
      if (ctx.model) map.get(k).carriers.add(ctx.model);
    } else if (type === 'Abilities') {
      if (!S.abilities.has(name)) S.abilities.set(name, { name, desc: ch.Description || Object.values(ch).join(' '), cond: isCondHidden(mods), src: ctx.upgrade || null });
    } else {
      if (!S.other.has(type)) S.other.set(type, new Map());
      S.other.get(type).set(name, { name, ch });
    }
  };
  const addRule = (r, link, ctx) => {
    if (!r || r.hidden) return;
    if (ctx && ctx.weapon) return; /* weapon rules are shown as keywords in the weapon table */
    const name = applyNameMods(r.name, link && link.modifiers);
    if (S.rules.has(name)) return;
    S.rules.set(name, { name, desc: r.description || '', cond: isCondHidden(link && link.modifiers) });
  };

  const walkInfo = (node, ctx) => {
    for (const p of arr(node.profiles)) addProfile(p, ctx, null);
    if (arr(node.profiles).some(p => /Weapons$/.test(p.typeName || ''))) ctx = Object.assign({}, ctx, { weapon: true });
    for (const r of arr(node.rules)) addRule(r, null, ctx);
    for (const il of arr(node.infoLinks)) {
      if (il.hidden || SKIP_RE.test(il.name || '')) continue;
      const t = resolve(il.targetId, scope);
      if (!t) continue;
      const n = t.node;
      if (il.type === 'profile') addProfile(Object.assign({}, n, { name: il.name || n.name }), ctx, il.modifiers);
      else if (il.type === 'rule') addRule(n, il, ctx);
      else if (il.type === 'infoGroup') walkInfo(n, ctx);
    }
    for (const g of arr(node.infoGroups)) if (!g.hidden && !SKIP_RE.test(g.name || '')) walkInfo(g, ctx);
  };

  /* Returns the model count range [min, max] for this node */
  const walk = (node, ctx, depth) => {
    if (!node || depth > 14) return [0, 0];
    if (node.hidden && depth > 0) return [0, 0];
    if (depth > 0 && SKIP_RE.test(node.name || '')) return [0, 0];
    const key = node._targetId || node.id;
    if (ctx.stack.includes(key)) return [0, 0];
    const c2 = Object.assign({}, ctx, { stack: ctx.stack.concat(key) });

    S.allIds.add(key);
    if (node.type === 'model') {
      c2.model = node.name; S.modelIds.add(key); S.modelNames.add(node.name);
      for (const l of arr(node.categoryLinks)) S.modelCatIds.add(l.targetId);
    }
    if (node.type === 'upgrade') c2.upgrade = node.name;
    walkInfo(node, c2);

    if (node.type === 'upgrade' && depth > 0) {
      const pc = costOf(node, Data.ptsId);
      if (pc) S.upgradeCosts.push({ name: node.name, pts: pc });
    }

    let lo = 0, hi = 0;
    const kids = [];
    for (const e of arr(node.selectionEntries)) kids.push(Object.assign({}, e, { _targetId: e.id }));
    for (const l of arr(node.entryLinks)) {
      if (l.type === 'selectionEntryGroup') { const d = deref(l, scope); if (d) kids.push(Object.assign(d, { _isGroup: true })); }
      else { const d = deref(l, scope); if (d) kids.push(d); }
    }
    for (const g of arr(node.selectionEntryGroups)) kids.push(Object.assign({}, g, { _isGroup: true, _targetId: g.id }));

    for (const k of kids) {
      if (k._isGroup) {
        if (k.hidden || SKIP_RE.test(k.name || '')) continue;
        const [glo, ghi, models] = walkGroup(k, c2, depth + 1);
        lo += glo; hi += ghi;
        if (models.length) S.comp.push({ group: k.name, min: glo, max: ghi, models });
      } else {
        const [clo, chi] = walk(k, c2, depth + 1);
        if (k.type === 'model' && !k.hidden) {
          const b = bounds(k);
          const mn = b.min != null ? b.min : 0, mx = b.max != null ? b.max : Math.max(mn, 1);
          lo += mn; hi += mx;
          if (!c2.inGroup) S.comp.push({ group: null, min: mn, max: mx, models: [{ name: k.name, min: mn, max: mx, pts: costOf(k, Data.ptsId) }] });
        } else { lo += clo; hi += chi; }
      }
    }
    return [lo, hi];
  };

  const walkGroup = (g, ctx, depth) => {
    const c2 = Object.assign({}, ctx, { inGroup: true });
    const models = [], choices = [];
    let lo = 0, hi = 0;
    const kids = [];
    for (const e of arr(g.selectionEntries)) kids.push(Object.assign({}, e, { _targetId: e.id }));
    for (const l of arr(g.entryLinks)) { const d = deref(l, scope); if (d) kids.push(Object.assign(d, l.type === 'selectionEntryGroup' ? { _isGroup: true } : {})); }
    for (const sg of arr(g.selectionEntryGroups)) kids.push(Object.assign({}, sg, { _isGroup: true, _targetId: sg.id }));
    for (const k of kids) {
      if (k.hidden || SKIP_RE.test(k.name || '')) continue;
      if (k._isGroup) {
        const [a, b, m] = walkGroup(k, c2, depth + 1);
        lo += a; hi += b; models.push(...m);
        if (!m.length) choices.push({ name: k.name, pts: 0, sub: true });
        continue;
      }
      walk(k, c2, depth + 1);
      if (k.type === 'model') {
        const b = bounds(k);
        const mn = b.min != null ? b.min : 0, mx = b.max != null ? b.max : Infinity;
        lo += mn; hi += mx;
        models.push({ name: k.name, min: mn, max: mx, pts: costOf(k, Data.ptsId) });
      } else {
        choices.push({ name: k.name, pts: costOf(k, Data.ptsId), def: g.defaultSelectionEntryId === k._targetId });
      }
    }
    S.allIds.add(g._targetId || g.id);
    if (models.length) S.modelGroupIds.add(g._targetId || g.id);
    const b = bounds(g);
    if (b.min != null) lo = Math.max(lo, b.min);
    if (b.max != null) hi = Math.min(hi, b.max);
    if (!models.length && choices.length) S.options.push({ group: g.name, min: b.min, max: b.max, choices, owner: ctx.model || null });
    return [lo, hi === Infinity ? lo : hi, models];
  };

  const root = u.node;
  const [mlo, mhi] = walk(root, { stack: [], model: root.type === 'model' ? root.name : null }, 0);
  S.models = root.type === 'model' ? [1, 1] : [mlo, Math.max(mlo, mhi)];
  S.points = pointsInfo(root, S);
  S.keywords = arr(root.categoryLinks).filter(l => !l.hidden && !/^Faction:/i.test(l.name) && l.name !== 'Configuration').map(l => l.name);
  S.factionKw = arr(root.categoryLinks).filter(l => /^Faction:/i.test(l.name)).map(l => l.name.replace(/^Faction:\s*/i, ''));
  S.assoc = arr(root.associations).map(a => ({ label: a.label || a.name, childName: a.childName, targets: assocTargets(a) }));
  sheetCache.set(key, S);
  return S;
}

/* ---------- points ---------- */
function flattenMods(node) {
  const out = [];
  for (const m of arr(node.modifiers)) out.push({ m, extra: [] });
  const visit = (g, extra) => {
    const ex = extra.concat(arr(g.conditions).length || arr(g.conditionGroups).length ? [{ type: 'and', conditions: arr(g.conditions), conditionGroups: arr(g.conditionGroups) }] : []);
    for (const m of arr(g.modifiers)) out.push({ m, extra: ex });
    for (const sg of arr(g.modifierGroups)) visit(sg, ex);
  };
  for (const g of arr(node.modifierGroups)) visit(g, []);
  return out;
}

/* Evaluates a condition knowing only the model count n. Returns true/false, or null when unknown. */
const UNIT_SCOPES = new Set(['self', 'parent', 'unit-self', 'root-entry']);
function isModelCountQuery(c, S) {
  if (c.field !== 'selections') return false;
  const unitScope = UNIT_SCOPES.has(c.scope) || c.scope === S.unit.node._targetId || S.allIds.has(c.scope);
  const modelChild = c.childId === 'model' || S.modelIds.has(c.childId) || S.modelGroupIds.has(c.childId) || S.modelCatIds.has(c.childId);
  return unitScope && modelChild;
}
function cmp(type, n, v) {
  switch (type) {
    case 'atLeast': return n >= v;
    case 'greaterThan': return n > v;
    case 'atMost': return n <= v;
    case 'lessThan': return n < v;
    case 'equalTo': return n === v;
    case 'notEqualTo': return n !== v;
    default: return null;
  }
}
function evalCond(c, n, S) {
  if (c.scope === 'primary-catalogue' && (c.type === 'instanceOf' || c.type === 'notInstanceOf')) {
    const is = S.unit.fac.id === c.childId;
    return c.type === 'instanceOf' ? is : !is;
  }
  if (!isModelCountQuery(c, S)) return null;
  return cmp(c.type, n, Number(c.value));
}
function describeCond(c, S) {
  let name = c.childName;
  if (!name && c.childId) { const r = resolve(c.childId, S.unit.fac.scope); name = r ? r.node.name : null; }
  if (!name) return null;
  const v = Number(c.value);
  if (c.type === 'instanceOf') return name;
  if (c.type === 'notInstanceOf') return `≠ ${name}`;
  const op = { atLeast: '≥', greaterThan: '>', atMost: '≤', lessThan: '<', equalTo: '=', notEqualTo: '≠' }[c.type] || c.type;
  return `${name} ${op} ${v}`;
}
function evalGroup(g, n, S) {
  const parts = arr(g.conditions).map(c => evalCond(c, n, S)).concat(arr(g.conditionGroups).map(x => evalGroup(x, n, S)));
  if (!parts.length) return true;
  if (g.type === 'or') { if (parts.some(p => p === true)) return true; if (parts.some(p => p === null)) return null; return false; }
  if (parts.some(p => p === false)) return false;
  if (parts.some(p => p === null)) return null;
  return true;
}

function pointsInfo(node, S) {
  const pid = Data.ptsId;
  const base = costOf(node, pid);
  const perModel = [];
  for (const c of S.comp) for (const m of c.models) if (m.pts) perModel.push(m);
  const mods = flattenMods(node).filter(x => x.m.field === pid);
  let unknown = false;
  const notes = new Map();
  const noteFor = (m, g) => {
    const conds = [];
    const visit = (x) => { for (const c of arr(x.conditions)) if (evalCond(c, 1, S) === null) conds.push(describeCond(c, S)); for (const y of arr(x.conditionGroups)) visit(y); };
    visit(g);
    const val = Number(m.value) || 0;
    const pts = costTypeName(Data.ptsId);
    const eff = m.type === 'set' ? `${val} ${pts}` : m.type === 'increment' ? `+${val} ${pts}` : m.type === 'decrement' ? `−${val} ${pts}` : null;
    if (!eff || !conds.length || conds.some(c => !c)) return;
    const txt = `${eff}: ${conds.join(g.type === 'or' ? ' | ' : ' & ')}`;
    notes.set(txt, true);
  };

  const at = (n) => {
    let v = base;
    if (perModel.length === 1) v += perModel[0].pts * n;
    for (const { m, extra } of mods) {
      const g = { type: 'and', conditions: arr(m.conditions), conditionGroups: arr(m.conditionGroups).concat(extra) };
      const ok = evalGroup(g, n, S);
      if (ok === null) { unknown = true; noteFor(m, g); continue; }
      if (!ok) continue;
      let times = 1;
      if (arr(m.repeats).length) {
        times = 0;
        for (const r of arr(m.repeats)) {
          if (!isModelCountQuery(r, S)) { times = null; break; }
          const per = Number(r.value) || 1;
          times += (r.roundUp ? Math.ceil(n / per) : Math.floor(n / per)) * (Number(r.repeats) || 1);
        }
        if (times === null) { unknown = true; continue; }
      }
      const val = Number(m.value) || 0;
      if (m.type === 'set') v = val;
      else if (m.type === 'increment') v += val * times;
      else if (m.type === 'decrement') v -= val * times;
    }
    return v;
  };

  const [lo, hi] = S.models;
  const tiers = [];
  const top = Math.min(hi, lo + 60);
  for (let n = Math.max(lo, 1); n <= Math.max(top, 1); n++) {
    const v = at(n);
    const last = tiers[tiers.length - 1];
    if (last && last.pts === v) last.to = n; else tiers.push({ from: n, to: n, pts: v });
  }
  if (!tiers.length) tiers.push({ from: lo, to: hi, pts: base });
  const min = Math.min(...tiers.map(t => t.pts));
  return { base, tiers, min, unknown, notes: [...notes.keys()], perModel: perModel.length > 1 ? perModel : [] };
}

/* =====================================================================
   Rule glossary (for weapon keywords)
   ===================================================================== */
const glossCache = new Map();
function glossary(fcat) {
  if (glossCache.has(fcat.id)) return glossCache.get(fcat.id);
  const g = new Map();
  for (const c of fcat.scope) {
    for (const r of arr(c.raw.sharedRules)) {
      const keys = [r.name].concat(arr(r.alias));
      for (const k of keys) if (k && !g.has(k.toLowerCase())) g.set(k.toLowerCase(), r);
    }
  }
  glossCache.set(fcat.id, g);
  return g;
}
function findRule(fcat, kw) {
  const g = glossary(fcat);
  let k = kw.trim().toLowerCase();
  if (g.has(k)) return g.get(k);
  const base = k.replace(/[\s-]*(\d+\+?|d\d+(\+\d+)?|x)$/i, '').trim();
  if (g.has(base)) return g.get(base);
  const anti = k.match(/^anti-/);
  if (anti && g.has('anti')) return g.get('anti');
  if (anti && g.has('anti-')) return g.get('anti-');
  return null;
}

