function parseHash() {
  const h = location.hash.replace(/^#\/?/, '').split('/').map(decodeURIComponent);
  const o = {};
  for (let i = 0; i < h.length - 1; i += 2) o[h[i]] = h[i + 1];
  if (h.includes('compare')) o.compare = true;
  return o;
}
function setHash(o, replace) {
  const parts = [];
  if (o.f) parts.push('f', o.f);
  if (o.t && o.t !== 'units') parts.push('t', o.t);
  if (o.u) parts.push('u', o.u);
  if (o.compare) parts.push('compare');
  const h = '#/' + parts.map(encodeURIComponent).join('/');
  if (location.hash === h) { route(); return; }
  if (replace) { history.replaceState(null, '', h); route(); } else location.hash = h;
}
