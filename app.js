(async function start() {
  const theme = store.get('theme', null);
  if (theme) document.documentElement.dataset.theme = theme;
  document.addEventListener('click', (e) => {
    if (e.target.closest('[data-reload]')) location.reload();
    if (e.target.closest('#updBtn')) checkForUpdate(true);
  });

  try {
    await loadData();
    await loadStratagems();
  } catch (err) {
    /* no local data at all: download it from GitHub, then reload */
    $('#loading').innerHTML = '<div class="spinner"></div><p id="firstLoad">Downloading data…</p>';
    checkForUpdate(true, () => location.reload());
    return;
  }

  try {
    initData();
    renderVersion();
    bind();
    renderTray();
    if (!location.hash || location.hash === '#' || location.hash === '#/') setHash({ f: (Data.cats[store.get('fac', '')] || Data.factions[0].cat).id }, true);
    else route();
  } catch (err) {
    console.error(err);
    $('#sheet').innerHTML = `<div class="empty"><h2>Error</h2><p>${esc(err.message)}</p></div>`;
    return;
  }
  setTimeout(() => checkForUpdate(false), 2000);
})();
