/* External rules text keeps only simple formatting tags */
const SAFE_TAGS = new Set(['B', 'I', 'U', 'BR', 'UL', 'OL', 'LI', 'DIV', 'P', 'STRONG', 'EM', 'SPAN']);
function safeHtml(html) {
  const t = document.createElement('template');
  t.innerHTML = String(html == null ? '' : html);
  const clean = (node) => {
    for (const ch of [...node.childNodes]) {
      if (ch.nodeType === 1) {
        if (!SAFE_TAGS.has(ch.tagName)) { ch.replaceWith(document.createTextNode(ch.textContent)); continue; }
        for (const a of [...ch.attributes]) ch.removeAttribute(a.name);
        clean(ch);
      } else if (ch.nodeType !== 3) ch.remove();
    }
  };
  clean(t.content);
  return t.innerHTML;
}

